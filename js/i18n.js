// Deutsch/Englisch. Schlüssel ist der deutsche Text – so bleibt der Code lesbar.
// Sprache: Einstellung „lang“ (auto | de | en); auto folgt der Sprache des Geräts.
const KEY = 'sb.settings';

function pref() {
  try { return JSON.parse(localStorage.getItem(KEY) || '{}').lang || 'auto'; } catch { return 'auto'; }
}

export function lang() {
  const p = pref();
  if (p === 'de' || p === 'en') return p;
  return /^de\b/i.test(navigator.language || '') ? 'de' : 'en';
}

export const isEn = () => lang() === 'en';
export const locale = () => (isEn() ? 'en-GB' : 'de-CH');

// t('Hallo {name}', { name }) → übersetzt, Platzhalter ersetzt; fehlt die Übersetzung, bleibt Deutsch.
export function t(de, vars) {
  let s = isEn() ? (EN[de] ?? de) : de;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
  return s;
}

// Statisches HTML: Elemente mit data-t (Text) bzw. data-t-attr="placeholder,aria-label" übersetzen.
export function translateDom(root = document) {
  document.documentElement.lang = lang();
  for (const el of root.querySelectorAll('[data-t]')) {
    el.dataset.de ??= el.textContent.trim();
    el.textContent = t(el.dataset.de);
  }
  for (const el of root.querySelectorAll('[data-t-attr]')) {
    for (const a of el.dataset.tAttr.split(',')) {
      const k = `de${a.replace(/(^|-)(\w)/g, (_, __, c) => c.toUpperCase())}`;
      el.dataset[k] ??= el.getAttribute(a) || '';
      el.setAttribute(a, t(el.dataset[k]));
    }
  }
}

